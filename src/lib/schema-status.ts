import "server-only";
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { SUPABASE_CONFIGURED } from "./env";
import { supabaseService } from "./supabase/admin";

// Which database updates (supabase/migrations) a deployment's database still needs, for the
// admin's Setup page. Databases from 20261025000100 on report their version through
// app_schema_version(); older ones are recognised by a column or function each update added.

export interface Migration {
  version: string;
  name: string;
  file: string;
}

export interface SchemaStatus {
  /** The latest update the database has, or null when it can't be read. */
  applied: string | null;
  /** Updates the database doesn't have yet, oldest first. */
  pending: Migration[];
}

const DIR = join(process.cwd(), "supabase/migrations");

/** The migration files shipped with this deployment, in order. */
export function migrationFiles(): Migration[] {
  try {
    return readdirSync(DIR)
      .filter((f) => /^\d{14}_[a-z0-9_]+\.sql$/.test(f))
      .sort()
      .map((f) => ({ version: f.slice(0, 14), name: f.slice(15, -4), file: f }));
  } catch {
    return [];
  }
}

type Client = ReturnType<typeof supabaseService>;

const column = (table: "store_settings", name: string) => async (sb: Client) => {
  const { error } = await sb.from(table).select(name).limit(1);
  return !error;
};

const fn = (name: string, args: Record<string, unknown>) => async (sb: Client) => {
  const { error } = await sb.rpc(name as never, args as never);
  // PGRST202: no such function. Any other answer (even "not allowed") means it exists.
  return error?.code !== "PGRST202";
};

/** For databases from before app_schema_version(): a sign of each update, newest first. */
const SIGNS: { version: string; present: (sb: Client) => Promise<boolean> }[] = [
  { version: "20261024000200", present: fn("resolve_store", { p_host: "" }) },
  { version: "20261024000100", present: column("store_settings", "store_id") },
  { version: "20261023000100", present: column("store_settings", "brand_color") },
  { version: "20261022000100", present: column("store_settings", "phone_login_enabled") },
  { version: "20261021000200", present: column("store_settings", "cart_reminders_enabled") },
  { version: "20261021000100", present: column("store_settings", "cod_confirmation") },
  { version: "20261020000200", present: column("store_settings", "whatsapp_enabled") },
  { version: "20261020000100", present: column("store_settings", "shiprocket_enabled") },
  { version: "20261019000100", present: fn("admin_product_list", { p: {} }) },
];

async function appliedVersion(): Promise<string | null> {
  const sb = supabaseService();
  const { data, error } = await sb.rpc("app_schema_version");
  if (!error && typeof data === "string") return data;
  if (error && error.code !== "PGRST202") return null;
  for (const sign of SIGNS) {
    if (await sign.present(sb)) return sign.version;
  }
  // The first set of migrations (the store itself works, so they're there).
  return (await column("store_settings", "id")(sb)) ? "20261018000900" : null;
}

export async function schemaStatus(): Promise<SchemaStatus> {
  if (!SUPABASE_CONFIGURED) return { applied: null, pending: [] };
  const applied = await appliedVersion().catch(() => null);
  if (!applied) return { applied: null, pending: [] };
  return { applied, pending: migrationFiles().filter((m) => m.version > applied) };
}

