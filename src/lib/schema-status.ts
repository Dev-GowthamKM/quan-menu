/**
 * The SQL to paste into Supabase's SQL editor: every pending update in order, recorded the
 * way the Supabase CLI records migrations (the same file `npm run db:bundle -- --since` writes).
 */
export function updateSql(status: SchemaStatus) {
  const parts = [
    `-- Taana: database update (migrations after ${status.applied}). Paste into Supabase › SQL Editor and Run, once.`,
    "-- Generated by Admin › Setup from supabase/migrations. It runs as one transaction: if anything fails, nothing changes.",
    "",
  ];
  for (const m of status.pending) {
    parts.push(`-- ===== ${m.file} =====`, readFileSync(join(DIR, m.file), "utf8").trimEnd(), "");
  }
  parts.push(
    "-- Record the migrations the way the Supabase CLI does.",
    "create schema if not exists supabase_migrations;",
    "create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);",
    `insert into supabase_migrations.schema_migrations (version, name) values\n${status.pending.map((m) => `  ('${m.version}', '${m.name}')`).join(",\n")}\non conflict (version) do nothing;`,
    "",
  );
  return parts.join("\n");
}
